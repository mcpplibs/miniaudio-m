#!/usr/bin/env python3
"""Write the module sources and the generated macro test from miniaudio.h.

- src/miniaudio.cppm exports every type, struct tag, enumerator and MA_API
  function of the API section of miniaudio.h by `export using` (the upstream
  globals, unchanged), each under the preprocessor condition the header
  declares it under; it declares the adaptations of the three `static
  MA_INLINE` functions in mcpplibs::mwrap::miniaudio and re-exports the
  macros module.
- src/inline.cpp defines those adaptations, each calling upstream's own.
- src/macros.cppm holds, in mcpplibs::mwrap::miniaudio::macros under their
  own names:
    * the value macros (MA_VERSION_*, MA_MAX_CHANNELS, MA_SIZE_MAX,
      MA_LISTENER_INDEX_CLOSEST …) as `inline constexpr` of the type of the
      macro's own expansion, the version string as a reference to a
      constexpr char array, each defined where the header defines it;
    * the compatibility names the header keeps as macros
      (ma_resource_manager_job → ma_job, ma_resource_manager_job_queue_init →
      ma_job_queue_init …): the types as aliases, the functions as constexpr
      references to the functions they name, the flag as a constant.
- tests/macros_mix_test.cpp checks each mapping against the raw header in a
  translation unit that includes it beside the import.

With --check, nothing is written and a difference fails.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import Surface, condition_text, fetch, surface  # noqa: E402

VERSION = '0.11.25'
NOTICE = (f'// Generated by tools/gen_exports.py from miniaudio {VERSION}\'s miniaudio.h — do not\n'
          '// edit by hand.\n')

# Macros that stay macros, in <mwrap/miniaudio/macros.hpp> (which is <miniaudio.h>), with the reason.
STRINGIFY = 'stringification'
DECLARES = 'declares a type by token pasting (the atomic wrappers ma_atomic_uint32 …, exported as types)'
ATTRIBUTE = 'an attribute, storage class or inline specifier of declarations'
PLATFORM = 'a platform test for conditional compilation (#ifdef)'
BACKEND = 'a backend test for conditional compilation (#ifdef); at run time ma_is_backend_enabled()'
CONFIG = 'a configuration switch for conditional compilation (#ifdef)'
SIDE_HEADER = {
    'MA_STRINGIFY': STRINGIFY, 'MA_XSTRINGIFY': STRINGIFY,
    'MA_ATOMIC': 'an alignment specifier of a declaration',
    'MA_ATOMIC_SAFE_TYPE_DECL': DECLARES, 'MA_ATOMIC_SAFE_TYPE_DECL_PTR': DECLARES,
    'MA_ATTRIBUTE_FORMAT': ATTRIBUTE, 'MA_FALLTHROUGH': 'a statement attribute', 'MA_INLINE': ATTRIBUTE,
    'MA_NO_INLINE': ATTRIBUTE, 'MA_GNUC_INLINE_HINT': ATTRIBUTE, 'MA_DLL_IMPORT': ATTRIBUTE,
    'MA_DLL_EXPORT': ATTRIBUTE, 'MA_DLL_PRIVATE': ATTRIBUTE, 'MA_API': ATTRIBUTE, 'MA_PRIVATE': ATTRIBUTE,
    'MA_NO_THREADING': CONFIG, 'MA_NO_RUNTIME_LINKING': CONFIG, 'MA_NO_RESOURCE_MANAGER': CONFIG,
}
PLATFORMS = ['MA_WIN32', 'MA_WIN32_UWP', 'MA_WIN32_GDK', 'MA_WIN32_NXDK', 'MA_WIN32_DESKTOP', 'MA_XBOX',
             'MA_XBOX_NXDK', 'MA_DOS', 'MA_POSIX', 'MA_UNIX', 'MA_LINUX', 'MA_APPLE', 'MA_BSD', 'MA_ANDROID',
             'MA_EMSCRIPTEN', 'MA_ORBIS', 'MA_PROSPERO', 'MA_3DS', 'MA_SWITCH', 'MA_BEOS', 'MA_HAIKU']
SIDE_HEADER.update({name: PLATFORM for name in PLATFORMS})
# Not mapped: the C library's.
NOT_MAPPED = {'NULL': "the C library's (the header defines it only where <stddef.h> did not)"}
# Not exported: a typedef the header writes for MSVC's C mode, a keyword in C++.
NOT_EXPORTED = {'wchar_t': 'a keyword in C++ (the typedef is for MSVC C without _WCHAR_T_DEFINED)'}

# The compatibility names the header keeps as macros (the resource manager's
# job queue became the general ma_job queue): what each names.
ALIAS_TYPES = ['ma_resource_manager_job', 'ma_resource_manager_job_queue_config', 'ma_resource_manager_job_queue']


def is_backend(name: str) -> bool:
    return name.startswith(('MA_SUPPORT_', 'MA_HAS_'))


def classify(sf: Surface):
    """(constants, alias types, alias functions); every other macro is listed."""
    for name in sf.macros:
        if is_backend(name):
            SIDE_HEADER.setdefault(name, BACKEND)
    constants, functions = [], []
    for name, macro in sf.macros.items():
        if name in SIDE_HEADER or name in NOT_MAPPED or name in ALIAS_TYPES:
            continue
        if macro.params is not None:
            sys.exit(f'{name}: a function-like macro without a decision')
        if any(not body for body in macro.bodies):
            sys.exit(f'{name}: an empty macro without a decision')
        if name.startswith('ma_'):
            if not all(b in sf.functions for b in macro.bodies):
                sys.exit(f'{name}: a lower-case macro that names no function: {macro.bodies}')
            functions.append(name)
        else:
            constants.append(name)
    return constants, [n for n in ALIAS_TYPES if n in sf.macros], functions


def emit_grouped(entries: list[tuple[str, str]]) -> list[str]:
    """`export using ::name;` lines, consecutive equal conditions in one #if."""
    out, current = [], None
    for name, cond in entries:
        if cond != current:
            if current:
                out.append('#endif')
            if cond:
                out.append(f'#if {cond}')
            current = cond
        out.append(f'export using ::{name};')
    if current:
        out.append('#endif')
    return out


def module_source(sf: Surface) -> str:
    types = [(n, condition_text(c)) for n, c in sf.types.items() if n not in NOT_EXPORTED]
    enumerators = [(n, condition_text(c)) for n, c in sf.enumerators.items()]
    functions = [(n, condition_text(c)) for n, c in sf.functions.items()]
    lines = [NOTICE.rstrip('\n'), '''//
// mcpplibs.mwrap.miniaudio — miniaudio, audio playback, capture, decoding,
// encoding, conversion, mixing and the high-level engine in one library, as a
// C++ module. Every exported name is the upstream global of <miniaudio.h>,
// unchanged: the types and struct tags, the enumerators of its enums, and
// every MA_API function (context, device, engine, sound, node graph, resource
// manager, decoder, encoder, data sources, converters, resamplers, filters,
// effects, ring buffers, logging, allocation). Each is exported under the
// condition the header declares it under: the POSIX thread types on POSIX,
// ma_IMMNotificationClient on Windows. The three `static MA_INLINE` functions
// are adapted in mcpplibs::mwrap::miniaudio (src/inline.cpp). The root also
// re-exports the macro mappings. The library is compat.miniaudio, built from
// the same release; the module includes only the declarations (no
// MINIAUDIO_IMPLEMENTATION).
module;
#include <miniaudio.h>

export module mcpplibs.mwrap.miniaudio;

export import mcpplibs.mwrap.miniaudio.macros;
''']
    lines.append(f'// types and struct tags ({len(types)})')
    lines += emit_grouped(types)
    lines.append('')
    lines.append(f'// enumerators ({len(enumerators)})')
    lines += emit_grouped(enumerators)
    lines.append('')
    lines.append(f'// MA_API functions ({len(functions)})')
    lines += emit_grouped(functions)
    lines.append('')
    lines.append(f'// The static MA_INLINE functions ({len(sf.inlines)}): internal linkage, not exportable;')
    lines.append('// adapted under the same names and signatures, each calling upstream\'s (src/inline.cpp).')
    lines.append('export namespace mcpplibs::mwrap::miniaudio {')
    for f in sf.inlines:
        if f.condition:
            sys.exit(f'{f.name}: a conditional inline function')
        lines.append(f'{f.returns} {f.name}({f.params});')
    lines.append('}  // namespace mcpplibs::mwrap::miniaudio')
    return '\n'.join(lines) + '\n'


def inline_source(sf: Surface) -> str:
    lines = [NOTICE.rstrip('\n'), '''//
// The adaptations of the `static MA_INLINE` functions of miniaudio.h: each
// calls upstream's own, which has internal linkage in this translation unit.
module;
#include <miniaudio.h>

module mcpplibs.mwrap.miniaudio;
''']
    for f in sf.inlines:
        lines.append(f'{f.returns} mcpplibs::mwrap::miniaudio::{f.name}({f.params}) {{ '
                     f'return ::{f.name}({", ".join(f.args)}); }}')
    return '\n'.join(lines) + '\n'


def macros_source(sf: Surface) -> str:
    constants, alias_types, alias_functions = classify(sf)
    lines = [NOTICE.rstrip('\n'), f'''//
// mcpplibs.mwrap.miniaudio.macros — the macros of miniaudio.h a named module
// cannot export as they are, under their original names in
// mcpplibs::mwrap::miniaudio::macros:
//
//   - {len(constants)} value macros as `inline constexpr`, each of the type its macro
//     expands to (MA_MAX_CHANNELS is an `int`, as 254 is; MA_SIZE_MAX a
//     `size_t`; MA_LISTENER_INDEX_CLOSEST an `ma_uint8`; MA_BACKEND_COUNT an
//     `int`), the version string as a reference to a constexpr char array.
//     Each is defined where the header defines it (#ifdef);
//   - the compatibility names the header keeps as macros: {len(alias_types)} types as
//     aliases of the types they name (ma_resource_manager_job is ma_job) and
//     {len(alias_functions)} functions as constexpr references to the functions they name
//     (ma_resource_manager_job_queue_init is ma_job_queue_init).
//
// {len(SIDE_HEADER)} macros stay macros — stringification, attributes and storage
// classes, the token-pasting type declarations, the platform and backend
// tests (MA_WIN32, MA_POSIX, MA_SUPPORT_*, MA_HAS_*) — in
// <mwrap/miniaudio/macros.hpp>, included before the import; NULL is the C
// library's. tools/check_exports.py accounts for every one.
module;
#include <miniaudio.h>

export module mcpplibs.mwrap.miniaudio.macros;

// The header's values and names, taken while its macros are defined (module linkage).
namespace mwrap_miniaudio_capture {{''']
    for name in constants:
        lines.append(f'#ifdef {name}')
        if name == 'MA_VERSION_STRING':
            lines.append(f'inline constexpr char value_{name}[] = {name};')
        else:
            lines.append(f'inline constexpr auto value_{name} = {name};')
        lines.append('#endif')
    for name in alias_types:
        lines += [f'#ifdef {name}', f'using type_{name} = {name};', '#endif']
    for name in alias_functions:
        lines += [f'#ifdef {name}', f'inline constexpr auto& value_{name} = {name};', '#endif']
    lines.append('}  // namespace mwrap_miniaudio_capture')
    lines.append('')
    lines.append('// The names, now free: each macro is undefined in this unit only.')
    for name in constants + alias_types + alias_functions:
        lines += [f'#ifdef {name}', f'#undef {name}', f'#define MWRAP_HAS_{name} 1', '#endif']
    lines.append('')
    lines.append('export namespace mcpplibs::mwrap::miniaudio::macros {')
    lines.append('namespace c = ::mwrap_miniaudio_capture;')
    lines.append('')
    lines.append(f'// value macros ({len(constants)})')
    for name in constants:
        ref = '&' if name == 'MA_VERSION_STRING' else ''
        lines += [f'#ifdef MWRAP_HAS_{name}', f'inline constexpr auto{ref} {name} = c::value_{name};', '#endif']
    lines.append('')
    lines.append(f'// compatibility type names ({len(alias_types)})')
    for name in alias_types:
        lines += [f'#ifdef MWRAP_HAS_{name}', f'using {name} = c::type_{name};', '#endif']
    lines.append('')
    lines.append(f'// compatibility function names ({len(alias_functions)})')
    for name in alias_functions:
        lines += [f'#ifdef MWRAP_HAS_{name}', f'inline constexpr auto& {name} = c::value_{name};', '#endif']
    lines.append('')
    lines.append('}  // namespace mcpplibs::mwrap::miniaudio::macros')
    return '\n'.join(lines) + '\n'


def mix_test_source(sf: Surface) -> str:
    constants, alias_types, alias_functions = classify(sf)
    lines = [NOTICE.rstrip('\n'), '''//
// Every mapping against the raw header, in one translation unit that includes
// <mwrap/miniaudio/macros.hpp> (that is, <miniaudio.h>) beside the import:
//
//   - each constant has its macro's type and value (the macro is set aside
//     with push_macro around the comparison: while it is defined it expands
//     even inside `m::NAME`);
//   - each compatibility type is the type its macro names, and each
//     compatibility function the very function its macro names.
#include <mwrap/miniaudio/macros.hpp>
#include <gtest/gtest.h>

import std;
import mcpplibs.mwrap.miniaudio;

namespace m = mcpplibs::mwrap::miniaudio::macros;

// ── the raw values, while the macros are defined ────────────────────────────''']
    for name in constants:
        if name == 'MA_VERSION_STRING':
            lines += [f'using raw_type_{name} = decltype({name});',
                      f'constexpr std::string_view raw_{name} = {name};']
        else:
            lines.append(f'constexpr auto raw_{name} = {name};')
    for name in alias_types:
        lines.append(f'using raw_type_{name} = {name};')
    for name in alias_functions:
        lines.append(f'constexpr auto* raw_{name} = &{name};')
    lines.append('')
    lines.append('// ── the module\'s, with each macro set aside ─────────────────────────────────')
    for name in constants + alias_types + alias_functions:
        lines += [f'#pragma push_macro("{name}")', f'#undef {name}']
    for name in constants:
        if name == 'MA_VERSION_STRING':
            lines.append(f'static_assert(std::is_same_v<decltype(m::{name}), const char (&)[sizeof(raw_type_{name})]>);')
            lines.append(f'static_assert(std::string_view(m::{name}) == raw_{name});')
        else:
            lines.append(f'static_assert(std::is_same_v<decltype(m::{name}), const decltype(raw_{name})>);')
            lines.append(f'static_assert(m::{name} == raw_{name});')
    for name in alias_types:
        lines.append(f'static_assert(std::is_same_v<m::{name}, raw_type_{name}>);')
    lines.append('')
    lines.append('TEST(MacrosMix, CompatibilityFunctionsAreTheFunctions) {')
    for name in alias_functions:
        lines.append(f'    EXPECT_EQ(&m::{name}, raw_{name});')
    lines.append('}')
    for name in reversed(constants + alias_types + alias_functions):
        lines.append(f'#pragma pop_macro("{name}")')
    return '\n'.join(lines) + '\n'


def outputs(root: Path) -> dict[Path, str]:
    sf = surface(fetch(root))
    return {
        root / 'src/miniaudio.cppm': module_source(sf),
        root / 'src/inline.cpp': inline_source(sf),
        root / 'src/macros.cppm': macros_source(sf),
        root / 'tests/macros_mix_test.cpp': mix_test_source(sf),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if a generated file differs')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, text in outputs(root).items():
        old = path.read_text(encoding='utf-8') if path.exists() else None
        if old == text:
            continue  # unchanged: keep the file (and its timestamp) as it is
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.write_bytes(text.encode('utf-8'))
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('stale generated sources (run tools/gen_exports.py): ' + ', '.join(stale))


if __name__ == '__main__':
    main()
