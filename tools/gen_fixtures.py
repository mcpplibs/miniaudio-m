#!/usr/bin/env python3
"""Write the decoder fixtures of tests/ (wrapper contributions, Apache-2.0).

tests/data/tone.wav is 0.1 s of a 440 Hz sine at half scale, mono, 44.1 kHz,
16-bit PCM, written here sample by sample. tests/data/tone.flac is the same
samples losslessly (ffmpeg's FLAC encoder), tests/data/tone.mp3 the same tone
at 64 kbit/s (ffmpeg with libmp3lame). tests/data/fixtures.inc holds the three
files as byte arrays, so the tests decode them from memory, and from a file
they write, on every target — wasm32-emscripten under node included.

The committed files are the measured ones: the tests read them, not this
script, which only needs to run again to change them.
"""
import math
from pathlib import Path
import struct
import subprocess

RATE, FRAMES, FREQ = 44100, 4410, 440.0


def main():
    data = Path(__file__).resolve().parents[1] / 'tests/data'
    data.mkdir(parents=True, exist_ok=True)
    samples = [round(0.5 * 32767 * math.sin(2 * math.pi * FREQ * n / RATE)) for n in range(FRAMES)]
    pcm = struct.pack(f'<{FRAMES}h', *samples)
    header = (b'RIFF' + struct.pack('<I', 36 + len(pcm)) + b'WAVE' +
              b'fmt ' + struct.pack('<IHHIIHH', 16, 1, 1, RATE, RATE * 2, 2, 16) +
              b'data' + struct.pack('<I', len(pcm)))
    (data / 'tone.wav').write_bytes(header + pcm)
    common = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-bitexact', '-i', str(data / 'tone.wav'),
              '-map_metadata', '-1']
    subprocess.run(common + ['-c:a', 'flac', str(data / 'tone.flac')], check=True)
    subprocess.run(common + ['-c:a', 'libmp3lame', '-b:a', '64k', '-write_xing', '0', '-id3v2_version', '0',
                             str(data / 'tone.mp3')], check=True)
    out = ['// Generated by tools/gen_fixtures.py from tests/data — do not edit by hand.']
    for name in ('tone.wav', 'tone.flac', 'tone.mp3'):
        raw = (data / name).read_bytes()
        ident = 'fixture_' + name.replace('.', '_')
        out.append(f'inline constexpr unsigned char {ident}[{len(raw)}] = {{')
        for i in range(0, len(raw), 20):
            out.append('    ' + ', '.join(f'0x{b:02x}' for b in raw[i:i + 20]) + ',')
        out.append('};')
    (data / 'fixtures.inc').write_text('\n'.join(out) + '\n', encoding='utf-8')
    for name in ('tone.wav', 'tone.flac', 'tone.mp3', 'fixtures.inc'):
        print(name, (data / name).stat().st_size)


if __name__ == '__main__':
    main()
